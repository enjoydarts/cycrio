import { createHash, randomUUID } from 'node:crypto';
import { mkdir, readFile, rename, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as icons from 'simple-icons';
import { normalizeBrandName } from '../src/lib/service-logo-normalize.ts';

const root = fileURLToPath(new URL('../', import.meta.url));
const catalog = JSON.parse(
  await readFile(
    resolve(root, 'node_modules/simple-icons/data/simple-icons.json'),
    'utf8',
  ),
);
const supplements = JSON.parse(
  await readFile(resolve(root, 'static/brand/services/sources.json'), 'utf8'),
);

// Atomic replacement prevents partially written assets during concurrent npm hooks.
// Unchanged files preserve their mtime so Vite does not loop on generated output.
async function writeChanged(path, content) {
  try {
    if ((await readFile(path, 'utf8')) === content) return;
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  await mkdir(dirname(path), { recursive: true });
  const temporary = `${path}.${randomUUID()}.tmp`;
  await writeFile(temporary, content);
  await rename(temporary, path);
}

const entriesBySlug = new Map();
const candidates = new Map();
function addCandidate(name, entry) {
  const key = normalizeBrandName(name);
  if (!candidates.has(key)) candidates.set(key, new Map());
  candidates.get(key).set(entry.slug, entry);
}

for (const icon of Object.values(icons)) {
  const { slug, title, hex, svg } = icon;
  const entry = { slug, title, src: `/service-logos/${slug}.svg` };
  const channels = hex.match(/../g).map((channel) => {
    const value = Number.parseInt(channel, 16) / 255;
    return value <= 0.04045 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4;
  });
  const luminance =
    channels[0] * 0.2126 + channels[1] * 0.7152 + channels[2] * 0.0722;
  if (luminance > 0.7) entry.background = 'dark';
  entriesBySlug.set(slug, entry);
  addCandidate(slug, entry);
  addCandidate(title, entry);
  await writeChanged(
    resolve(root, `static/service-logos/${slug}.svg`),
    svg.replace('<svg ', `<svg fill="#${hex}" `) + '\n',
  );
}
// Every source name participates in collision detection, including canonical slugs.
for (const metadata of catalog) {
  const entry = entriesBySlug.get(metadata.slug);
  for (const alias of metadata.aliases?.aka ?? []) {
    addCandidate(alias, entry);
  }
}
for (const supplement of supplements) {
  const { slug, title, file, sha256 } = supplement;
  const bytes = await readFile(resolve(root, `static/brand/services/${file}`));
  if (createHash('sha256').update(bytes).digest('hex') !== sha256) {
    throw new Error(`Supplement logo checksum mismatch: ${file}`);
  }
  // Update the same slug in place so all its previously registered aliases use
  // the official supplement without selecting among different brands.
  const entry = entriesBySlug.get(slug) ?? {};
  delete entry.background;
  Object.assign(entry, { slug, title, src: `/brand/services/${file}` });
  entriesBySlug.set(slug, entry);
  for (const name of [slug, title]) addCandidate(name, entry);
}
const index = {};
const ambiguousNames = [];
for (const [key, matches] of candidates) {
  if (matches.size === 1) index[key] = matches.values().next().value;
  else ambiguousNames.push({ key, slugs: [...matches.keys()].sort() });
}
ambiguousNames.sort((a, b) => a.key.localeCompare(b.key, 'en'));
const sorted = Object.fromEntries(
  Object.entries(index).sort(([a], [b]) => a.localeCompare(b, 'en')),
);
await writeChanged(
  resolve(root, 'src/lib/generated/service-logo-index.ts'),
  '// Generated by scripts/generate-service-logos.mjs; do not edit.\n' +
    "export const serviceLogoIndex: Record<string, { slug: string; title: string; src: string; background?: 'dark' }> = " +
    JSON.stringify(sorted) +
    ';\n',
);
// Preserve upstream per-icon source/license data alongside the locally served assets.
await writeChanged(
  resolve(root, 'static/service-logos/catalog.json'),
  JSON.stringify({
    package: 'simple-icons@16.36.0',
    icons: catalog,
    ambiguousNames,
  }) + '\n',
);
await writeChanged(
  resolve(root, 'static/service-logos/LICENSE.txt'),
  await readFile(resolve(root, 'node_modules/simple-icons/LICENSE.md'), 'utf8'),
);
